-- ------------------------------------------------------------
-- 4) Policies
--    Content tables: anyone can READ, only admin can WRITE.
-- ------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['profile','stats','skills','projects','experience','certificates']
  loop
    execute format('drop policy if exists "public read" on public.%I;', t);
    execute format('drop policy if exists "admin write" on public.%I;', t);
    execute format('create policy "public read" on public.%I for select using (true);', t);
    execute format('create policy "admin write" on public.%I for all using (public.is_admin()) with check (public.is_admin());', t);
  end loop;
end $$;

--    Messages: only the server-side contact Edge Function can submit;
--    only the admin can READ/delete. The function uses the service role key.
drop policy if exists "anyone submit" on public.messages;
drop policy if exists "admin read"    on public.messages;
drop policy if exists "admin delete"  on public.messages;
create policy "admin read"    on public.messages for select using (public.is_admin());
create policy "admin delete"  on public.messages for delete using (public.is_admin());

